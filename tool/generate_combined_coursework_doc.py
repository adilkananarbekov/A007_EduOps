def generate_markdown(sections: list[dict]) -> str:
    lines = [
        "# Курсовая документация по проекту EduOps",
        "",
        "## Паспорт документа",
        "",
        "- Проект: EduOps",
        "- Формат: единая документация по React и Flutter частям",
        "- Выполнили: Албарсбеков Азим (React), Анарбеков Адилкан (Flutter)",
        "- Учебное заведение: Ala-Too College of IT and Business",
        "- Курс: 3",
        "",
    ]
    for section in sections:
        lines.append(f"## {section['title']}")
        lines.append("")
        for paragraph in section.get("paragraphs", []):
            lines.append(paragraph)
            lines.append("")
        for bullet in section.get("bullets", []):
            lines.append(f"- {bullet}")
        if section.get("bullets"):
            lines.append("")
        for index, item in enumerate(section.get("numbers", []), start=1):
            lines.append(f"{index}. {item}")
        if section.get("numbers"):
            lines.append("")
        if section.get("table"):
            headers = section["table"]["headers"]
            rows = section["table"]["rows"]
            lines.append("| " + " | ".join(headers) + " |")
            lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
            for row in rows:
                lines.append("| " + " | ".join(row) + " |")
            lines.append("")
        if section.get("code"):
            lines.append("```text")
            lines.append(section["code"].strip("\n"))
            lines.append("```")
            lines.append("")
    return "\n".join(lines).strip() + "\n"


def generate_docx(sections: list[dict]) -> None:
    document = Document()
    configure_document(document)
    add_title_page(document)

    for index, section in enumerate(sections):
        heading = document.add_heading(section["title"], level=1)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER if section["title"] in {"Аннотация", "Содержание"} else WD_ALIGN_PARAGRAPH.LEFT
        for paragraph in section.get("paragraphs", []):
            add_body_paragraph(document, paragraph)
        for bullet in section.get("bullets", []):
            add_bullet(document, bullet)
        for item in section.get("numbers", []):
            add_number(document, item)
        if section.get("table"):
            add_table(document, section["table"]["headers"], section["table"]["rows"])
        if section.get("code"):
            add_code_block(document, section["code"])
        if index < len(sections) - 1:
            document.add_paragraph()

    document.save(DOCX_PATH)


